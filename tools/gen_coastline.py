#!/usr/bin/env python3
"""Generate lib/radar_core/src/coastline_data.cpp from US Census data.

Source: US Census Bureau cartographic boundary file cb_2023_us_state_500k
(1:500,000 scale, public domain). Only the main Hawaiian islands are kept,
then each ring is simplified with Douglas-Peucker.

Usage:
    pip install pyshp
    curl -LO https://www2.census.gov/geo/tiger/GENZ2023/shp/cb_2023_us_state_500k.zip
    unzip cb_2023_us_state_500k.zip -d cb
    python3 tools/gen_coastline.py cb/cb_2023_us_state_500k
"""

import math
import os
import sys

import shapefile  # pyshp

# Keep islands within this distance of KOA (nautical miles).
CENTER = (19.7388, -156.0456)
MAX_DIST_NM = 260
MIN_POINTS = 8
TOLERANCE_M = 120.0

NAMES = [
    ((19.6, -155.5), "Hawaii"),
    ((20.8, -156.3), "Maui"),
    ((20.55, -156.6), "Kahoolawe"),
    ((20.83, -156.93), "Lanai"),
    ((21.13, -157.0), "Molokai"),
    ((21.47, -157.98), "Oahu"),
    ((22.07, -159.5), "Kauai"),
    ((21.9, -160.15), "Niihau"),
]


def dist_nm(a, b):
    p1, p2 = math.radians(a[0]), math.radians(b[0])
    dp = p2 - p1
    dl = math.radians(b[1] - a[1])
    s = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * 3440.065 * math.atan2(math.sqrt(s), math.sqrt(1 - s))


def to_xy(pt, lat0):
    # Local equirectangular metres, good enough for simplification.
    lat, lon = pt
    return (math.radians(lon) * math.cos(math.radians(lat0)) * 6371000.0,
            math.radians(lat) * 6371000.0)


def seg_dist(p, a, b):
    ax, ay = a
    bx, by = b
    px, py = p
    dx, dy = bx - ax, by - ay
    if dx == 0 and dy == 0:
        return math.hypot(px - ax, py - ay)
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - (ax + t * dx), py - (ay + t * dy))


def simplify(points, tol):
    lat0 = points[0][0]
    xy = [to_xy(p, lat0) for p in points]
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        s, e = stack.pop()
        best, idx = 0.0, -1
        for i in range(s + 1, e):
            d = seg_dist(xy[i], xy[s], xy[e])
            if d > best:
                best, idx = d, i
        if best > tol and idx > 0:
            keep[idx] = True
            stack.append((s, idx))
            stack.append((idx, e))
    return [p for p, k in zip(points, keep) if k]


def island_name(ring):
    lat = sum(p[0] for p in ring) / len(ring)
    lon = sum(p[1] for p in ring) / len(ring)
    return min(NAMES, key=lambda n: dist_nm(n[0], (lat, lon)))[1]


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(1)
    reader = shapefile.Reader(sys.argv[1])
    rings = []
    for sr in reader.iterShapeRecords():
        if sr.record["STUSPS"] != "HI":
            continue
        shape = sr.shape
        parts = list(shape.parts) + [len(shape.points)]
        for i in range(len(parts) - 1):
            pts = [(lat, lon) for lon, lat in shape.points[parts[i]:parts[i + 1]]]
            if len(pts) < MIN_POINTS:
                continue
            if min(dist_nm(CENTER, p) for p in pts) > MAX_DIST_NM:
                continue
            simp = simplify(pts, TOLERANCE_M)
            if len(simp) >= MIN_POINTS:
                rings.append(simp)
    rings.sort(key=len, reverse=True)

    out_path = os.path.join(os.path.dirname(__file__), "..", "lib", "radar_core", "src",
                            "coastline_data.cpp")
    total = 0
    with open(out_path, "w") as f:
        f.write("// Generated by tools/gen_coastline.py - do not edit.\n")
        f.write("// Source: US Census Bureau cb_2023_us_state_500k (public domain),\n")
        f.write(f"// simplified to {TOLERANCE_M:.0f} m.\n")
        f.write('#include "places.h"\n\nnamespace radar {\nnamespace {\n\n')
        for n, ring in enumerate(rings):
            f.write(f"const float kRing{n}[] = {{  // {island_name(ring)}\n")
            for i in range(0, len(ring), 4):
                chunk = ring[i:i + 4]
                f.write("    " + " ".join(f"{la:.5f}f, {lo:.5f}f," for la, lo in chunk) + "\n")
            f.write("};\n\n")
            total += len(ring)
        f.write("}  // namespace\n\nconst CoastPolygon kCoastline[] = {\n")
        for n, ring in enumerate(rings):
            f.write(f'    {{"{island_name(ring)}", kRing{n}, {len(ring)}}},\n')
        f.write("};\n\nconst size_t kCoastlineCount = sizeof(kCoastline) / sizeof(kCoastline[0]);\n\n")
        f.write("}  // namespace radar\n")
    print(f"wrote {len(rings)} rings, {total} points -> {os.path.normpath(out_path)}")


if __name__ == "__main__":
    main()
