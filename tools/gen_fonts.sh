#!/usr/bin/env bash
# Regenerates the LVGL bitmap fonts in src/ui/fonts/ from the IBM Plex TTFs in
# docs/design/assets/ (SIL OFL). Needs Node.js; lv_font_conv is fetched by npx.
#
#   tools/gen_fonts.sh
set -euo pipefail
cd "$(dirname "$0")/.."

CONV=${LV_FONT_CONV:-"npx --yes lv_font_conv@1.5.3"}
ASSETS=docs/design/assets
OUT=src/ui/fonts
mkdir -p "$OUT"

# ASCII plus the few typographic glyphs the UI uses:
# degree, middle dot, em dash, right single quote, ellipsis, arrows.
FULL="-r 0x20-0x7E -r 0xB0,0xB7,0x2014,0x2019,0x2026,0x2190-0x2193"
DIGITS="-r 0x20,0x30-0x39"

gen() {  # name ttf size ranges...
  local name=$1 ttf=$2 size=$3
  shift 3
  # shellcheck disable=SC2086
  $CONV --font "$ASSETS/$ttf" $@ --size "$size" --bpp 4 --format lvgl --no-compress \
    --lv-include lvgl.h --lv-font-name "$name" -o "$OUT/$name.c"
  echo "$name"
}

for s in 10 11 12 13 14 16; do gen "plex_mono_$s" PlexMono-Medium.ttf "$s" $FULL; done
gen plex_reg_18 PlexCondensed-Regular.ttf 18 $FULL
for s in 16 18 20; do gen "plex_med_$s" PlexCondensed-Medium.ttf "$s" $FULL; done
for s in 14 16 18 20 26 29 32 36 46 53; do gen "plex_semi_$s" PlexCondensed-SemiBold.ttf "$s" $FULL; done
gen plex_semi_66 PlexCondensed-SemiBold.ttf 66 $DIGITS

{
  echo "// Generated by tools/gen_fonts.sh - IBM Plex (SIL OFL 1.1), 4 bpp."
  echo "#pragma once"
  echo "#include <lvgl.h>"
  for f in "$OUT"/plex_*.c; do echo "LV_FONT_DECLARE($(basename "$f" .c))"; done
} > "$OUT/fonts.h"
